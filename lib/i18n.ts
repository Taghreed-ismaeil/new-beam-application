type Params = Record<string, string | number | null | undefined>;

function interpolate(str: string, params?: Params): string {
  if (!params) return str;
  return str.replace(/\{(\w+)\}/g, (m, key) => {
    const v = params[key];
    return v === undefined || v === null ? m : String(v);
  });
}

/** Arabic count-form picker: zero / one / two / few (3-10) / many (11+). */
function arForm(
  n: number,
  forms: { zero?: string; one: string; two?: string; few?: string; many?: string },
) {
  if (n === 0 && forms.zero) return forms.zero;
  if (n === 1) return forms.one;
  if (n === 2 && forms.two) return forms.two;
  if (n >= 3 && n <= 10 && forms.few) return forms.few;
  return forms.many ?? forms.few ?? forms.one;
}

