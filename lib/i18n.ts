type NamePickable = { name?: string | null; nameEn?: string | null } | null | undefined;

type I18nContextValue = {
  lang: Lang;
  t: (key: string, params?: Params) => string;
  tn: (key: string, count: number, params?: Params) => string;
  pick: (obj: NamePickable) => string;
  toggle: () => void;
  setLang: (lang: Lang) => void;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("ar");

  useEffect(() => {
    AsyncStorage.getItem(STORAGE_KEY).then((raw) => {
      if (raw === "ar" || raw === "en") setLangState(raw);
    });
  }, []);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    AsyncStorage.setItem(STORAGE_KEY, next).catch(() => {});
  }, []);

  const toggle = useCallback(() => {
    setLangState((prev) => {
      const next: Lang = prev === "ar" ? "en" : "ar";
      AsyncStorage.setItem(STORAGE_KEY, next).catch(() => {});
      return next;
    });
  }, []);

  const t = useCallback(
    (key: string, params?: Params) => {
      const str = STRINGS[lang][key];
      if (str === undefined) return key;
      return interpolate(str, params);
    },
    [lang],
  );

  const tn = useCallback(
    (key: string, count: number, params?: Params) => {
      const fn = PLURALS[lang][key];
      if (fn) return fn(count, params);
      const str = STRINGS[lang][key];
      if (str === undefined) return key;
      return interpolate(str, { count, ...params });
    },
    [lang],
  );

  const pick = useCallback(
    (obj: NamePickable) => {
      if (!obj) return "";
      if (lang === "ar") return obj.name || obj.nameEn || "";
      return obj.nameEn || obj.name || "";
    },
    [lang],
  );

  const value = useMemo(
    () => ({ lang, t, tn, pick, toggle, setLang }),
    [lang, t, tn, pick, toggle, setLang],
  );

  return React.createElement(I18nContext.Provider, { value }, children);
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}

/**
 * Manual RTL helpers for a primarily-Arabic UI. The app never calls
 * I18nManager.forceRTL (that requires a full reload), so RTL is produced by
 * hand: row-reversed flex direction, right-aligned text, and mirrored chevrons.
 */
export function useDirection() {
  const { lang } = useI18n();
  const isRTL = lang === "ar";

  return useMemo(
    () => ({
      isRTL,
      row: { flexDirection: isRTL ? ("row-reverse" as const) : ("row" as const) },
      text: {
        textAlign: isRTL ? ("right" as const) : ("left" as const),
        writingDirection: isRTL ? ("rtl" as const) : ("ltr" as const),
      },
      /** Points toward "back" / previous — left in LTR, right in RTL. */
      back: isRTL ? ("chevron-forward" as const) : ("chevron-back" as const),
      /** Points toward "forward" / into content — right in LTR, left in RTL. */
      chevron: isRTL ? ("chevron-back" as const) : ("chevron-forward" as const),
    }),
    [isRTL],
  );
}
